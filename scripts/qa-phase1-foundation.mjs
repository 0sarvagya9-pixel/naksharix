import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (p) => readFileSync(p, "utf8");
const cache = read("lib/redis.ts");
const cacheIndex = read("lib/cache/index.ts");
assert.ok(cache.includes("const value = await factory()") && cache.includes("return value;"), "Cache factory path missing");
assert.equal((cache.match(/await factory\(\)/g) || []).length, 1, "Redis cache must have one awaited factory invocation in the Redis code path");
assert.ok(cache.includes("const value = await factory();\n  try {"), "Factory must be outside cache-write retry handling");
assert.ok(cacheIndex.includes("cached !== null"), "False and zero cache values must remain hits");
const instrumentation = read("instrumentation.ts");
assert.ok(instrumentation.includes("Instrumentation.onRequestError"), "Next request error hook missing");
assert.ok(instrumentation.includes('logger.error("next.request.failure"'), "Structured error log missing");
for(const x of ["_error", "_request", "safeRoute", "routeType"])assert.ok(instrumentation.includes(x), "Safe error metadata missing: " + x);
assert.ok(!instrumentation.includes("request.url") && !instrumentation.includes("error.message") && !instrumentation.includes("error.stack"), "Error instrumentation might expose personal information");
const globalError = read("app/global-error.tsx");
assert.ok(globalError.includes('role="alert"') && globalError.includes('onClick={reset}') && globalError.includes('<html lang="en">'), "Global error recovery inaccessible");
const nav = read("components/main-nav.tsx");
const layout = read("app/layout.tsx");
assert.ok(nav.includes("setOpen(false);\n  }, [pathname]"), "Mobile navigation may remain open after route change");
assert.ok(nav.includes('locale === "hi" ? "पूजा"') && nav.includes('{navText(item.label)}'), "Shared nav Hindi labels must translate without claiming full website translation");
assert.ok(nav.includes('aria-label="Navigation menu"') && nav.includes("overscroll-contain"), "Mobile dialog accessibility regression");
assert.ok(layout.includes('href="#main-content"') && layout.includes('id="main-content"'), "Missing keyboard skip-to-content link");
console.log("PHASE1_FOUNDATION=PASS;CACHE_SINGLE_INVOCATION=YES;PRIVATE_ERROR_DATA_LOGGED=NO;MOBILE_A11Y=YES");
